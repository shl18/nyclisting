interface Station {
  name: string;
  latitude: number;
  longitude: number;
  lines: string[];
  distance?: number;
}

function deduplicateStations(stations: Station[]): Station[] {
  const stationMap = new Map<string, Station>();

  for (const station of stations) {
    const existingStation = stationMap.get(station.name);
    if (existingStation) {
      // Merge lines arrays and remove duplicates
      existingStation.lines = [
        ...new Set([...existingStation.lines, ...station.lines]),
      ];
    } else {
      stationMap.set(station.name, { ...station });
    }
  }

  return Array.from(stationMap.values());
}

