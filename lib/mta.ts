// Deduplicated version of all stations
const ALL_STATIONS = deduplicateStations(ALL_STATIONS_RAW);

export function getNearbyStations(
  latitude: number,
  longitude: number
): Station[] {
  return ALL_STATIONS.map((station) => ({
    ...station,
    distance: calculateDistance(
      latitude,
      longitude,
      station.latitude,
      station.longitude
    ),
  }))
    .sort((a, b) => (a.distance || 0) - (b.distance || 0))
    .slice(0, 3);
}

function calculateDistance(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 3959; // Earth's radius in miles
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) *
      Math.cos(toRad(lat2)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

function toRad(degrees: number): number {
  return degrees * (Math.PI / 180);
}

